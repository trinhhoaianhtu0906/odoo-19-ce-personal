def english(text):
    """English source of a Vietnamese caption or report text."""
    if text in CAPTIONS:
        return CAPTIONS[text]
    if text in REPORT_TEXT:
        return REPORT_TEXT[text]
    raise KeyError(f"No English text for: {text!r}")


def vietnamese_by_english():
    """{English: Vietnamese}; fails if two Vietnamese texts share one English text."""
    result = {}
    for vi, en in list(CAPTIONS.items()) + list(REPORT_TEXT.items()):
        if en in result and result[en] != vi:
            raise ValueError(f"{en!r} is used for {result[en]!r} and {vi!r}")
        result[en] = vi
    return result
